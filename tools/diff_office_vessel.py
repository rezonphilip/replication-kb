# usage: python3 -I diff_office_vessel.py <staged_root> <kb_root> <Project> [<Project> ...]
# Compares every file of <Project>--PAL.DatabaseScripts.Office with its Vessel counterpart
# (paired by top folder + name without number prefix, case/spaces ignored) and writes
# inventory/ms-rep-db-files.md: one row per file with its Office/Vessel status, so every
# script is accounted for. Lists file names and statuses only - never file contents.
import os, re, glob, sys

def read(p):
    b = open(p, 'rb').read()
    if b[:2] in (b'\xff\xfe', b'\xfe\xff'):
        t = b.decode('utf-16')
    else:
        try:
            t = b.decode('utf-8-sig')
        except UnicodeDecodeError:
            t = b.decode('latin-1')
    return t.replace('\r\n', '\n').replace('\r', '\n')

def key(rel):
    d, f = rel.split('/', 1) if '/' in rel else ('', rel)
    return (d, re.sub(r'^\d+_', '', os.path.basename(rel)).upper().replace(' ', ''), os.path.dirname(rel).upper())

def norm(t):
    return [re.sub(r'\s+', ' ', l).strip() for l in t.split('\n') if l.strip()]

root, kb, projects = sys.argv[1], sys.argv[2], sys.argv[3:]
rows, totals = [], {}
for proj in projects:
    O = os.path.join(root, f'{proj}--PAL.DatabaseScripts.Office')
    V = os.path.join(root, f'{proj}--PAL.DatabaseScripts.Vessel')
    of = {key(os.path.relpath(p, O)): os.path.relpath(p, O) for p in glob.glob(O + '/**/*', recursive=True) if os.path.isfile(p)}
    vf = {key(os.path.relpath(p, V)): os.path.relpath(p, V) for p in glob.glob(V + '/**/*', recursive=True) if os.path.isfile(p)}
    for k in sorted(of.keys() | vf.keys(), key=lambda k: (k[2], k[1])):
        a, b = of.get(k), vf.get(k)
        if a and not b:
            st = 'office only'
        elif b and not a:
            st = 'vessel only'
        else:
            ta, tb = read(os.path.join(O, a)), read(os.path.join(V, b))
            st = 'identical' if ta == tb else ('whitespace only' if norm(ta) == norm(tb) else 'different')
            if a != b:
                st += ', renumbered/renamed'
        totals[(proj, st)] = totals.get((proj, st), 0) + 1
        rows.append((proj, a or '—', b or '—', st))

out = ['---', 'doc_id: INV-MSREP-DB-FILES', 'type: inventory', 'mechanism: [smartsync, priority-replication]',
       'components: [RepIntegration, RepTransfer]',
       'sources: ["MS-REP database scripts snapshot staged 2026-11-11 (no git commit available)"]',
       'status: draft', 'author: claude', 'reviewed_by: ""', 'last_verified: 2026-11-11', '---', '',
       '# MS-REP database script files — Office vs Vessel status', '',
       'Every file in the RepIntegration and RepTransfer `PAL.DatabaseScripts.Office` / `.Vessel` projects, paired by name, '
       'with whether the two copies are identical. Generated by `tools/diff_office_vessel.py`. What each difference means is '
       'explained in DATA-MSREP-OFFVSL; what each object is, in INV-MSREP-DB. V2V objects belong to a dropped feature. '
       'Keywords: script file list, office vs vessel, file status.', '',
       '| Project | Status | Files |', '|---|---|---|']
out += [f'| {p} | {s} | {n} |' for (p, s), n in sorted(totals.items())]
out += ['', '| Project | Office file | Vessel file | Status |', '|---|---|---|---|']
out += [f'| {p} | `{a}` | `{b}` | {s} |' for p, a, b, s in rows]
open(os.path.join(kb, 'inventory', 'ms-rep-db-files.md'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'rows', totals)
