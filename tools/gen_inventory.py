import json,sys
d=json.load(open(sys.argv[1]))
# usage: python3 -I gen_inventory.py <extract.json> <repo_name> <groups.yaml> <kb_root>
# groups.yaml: {order: [group names...], groups: {ServiceName: group name}}
import yaml
G=yaml.safe_load(open(sys.argv[3])); GROUP=G['groups']; order=G['order']
META=G.get('meta',{})
DOC=META.get('doc_id','INV-MSREP'); TITLE=META.get('title','MS-REP'); MECH=META.get('mechanism','[smartsync, priority-replication, irep]'); NOTES=META.get('notes')
d={k:v for k,v in d.items() if k in GROUP}
REPO=sys.argv[2]; KB=sys.argv[4]
SECRET=('KEY','CONNECTION_STRING','PASSWORD','TOKEN')
def u(v,k):
  seen={}
  for name,src in v.get(k,[]):
    seen.setdefault(name,src)
  return seen
out=[]
out.append('''---
doc_id: '''+DOC+'''
type: inventory
mechanism: '''+MECH+'''
components: ['''+REPO+''']
sources: ["'''+TITLE+''' snapshot staged 2026-11-11 (no git commit available)"]
status: draft
author: claude
reviewed_by: ""
last_verified: 2026-11-11
---

# '''+TITLE+''' inventory

Machine-extracted list of what each '''+TITLE+''' service exposes. Keywords: inventory, routes, stored procedures, CO_Parameters, log file.

This file is the factual base the articles cite. It was generated by scanning controllers, repositories, `SqlNamedQueries.cs`, `appsettings.json` and logger calls. Values of configuration keys are never recorded, only their names. Parameter names that hold secrets are marked **(secret: never copy the value)**.

## Service groups

How the '''+str(len(d))+''' services divide by role, as confirmed by the platform team on 2026-11-11. Keywords: grouping, SmartSync, Priority Replication, iRep, adapter, orchestrator.

| Group | Services |
|---|---|
''')
for g in order:
  out.append(f"| {g} | {', '.join(s for s in d if GROUP.get(s)==g)} |\n")
out.append('\n'+(NOTES or '''
- **SmartSync** is the name of the transport mechanism (Service Bus messaging + Azure Blob upload/download). It is shared by all replication mechanisms.
- **RepTransfer** is an adapter over the transport; it serves Priority Replication and may serve iRep transfer flows.
- **RepIntegration** orchestrates Priority Replication end to end and handles only the *transfer* part of iRep (not iRep data preparation, ingestion or packet creation).
- **RepDBLogW** is the database gateway of Priority Replication; iRep may occasionally call it to read data.
''')+'\n')
for s in sorted(d, key=lambda s:(order.index(GROUP[s]),s)):
  v=d[s]
  out.append(f"## {s}\n\n{GROUP[s]}. Keywords: {s}, {s.replace('Rep','').lower()}, routes, stored procedures.\n\n")
  hs=u(v,'hosted')
  if hs: out.append('**Background loop / timers:** '+', '.join(f'`{n}` (`{src}`)' for n,src in list(hs.items())[:8])+'\n\n')
  r=u(v,'route')
  if r:
    out.append("**Routes** (controller route names):\n\n"+"\n".join(f"- `{n}` — `{src}`" for n,src in r.items())+"\n\n")
  a={k:x for k,x in u(v,'apiurl').items() if k!='application/json'}
  if a:
    out.append("**Calls other services** (route fragments found in code):\n\n"+"\n".join(f"- `{n}` — `{src}`" for n,src in a.items())+"\n\n")
  sp=u(v,'sp')
  if sp:
    out.append("**Stored procedures / SQL objects referenced:**\n\n"+"\n".join(f"- `{n}` — `{src}`" for n,src in sorted(sp.items()))+"\n\n")
  p=u(v,'param')
  if p:
    out.append("**CO_Parameters / parameter keys read:**\n\n"+"\n".join(f"- `{n}`"+(" **(secret: never copy the value)**" if any(x in n for x in SECRET) else "")+f" — `{src}`" for n,src in sorted(p.items()))+"\n\n")
  c=u(v,'cfg')
  if c:
    out.append("**appsettings sections bound:** "+", ".join(f"`{n}`" for n in sorted(c))+"\n\n")
  lg=v.get('log',[])
  out.append(f"**Logger calls found:** {len(lg)} (full list in `inventory/'+REPO+'-logs.md`).\n\n")
open(f'{KB}/inventory/{REPO}.md','w').write(''.join(out))
# logs file
L=['---\ndoc_id: '+DOC+'-LOGS\ntype: inventory\ncomponents: ['+REPO+']\nstatus: draft\nauthor: claude\nlast_verified: 2026-11-11\n---\n\n# '+TITLE+' log message catalogue\n\nEvery logger call and thrown exception found in '+TITLE+' code, per service, with level and source line. Services are configured with Serilog minimum level Error, so only Error/Critical lines (and unhandled exceptions) reach the log file by default; Information, Debug and Warning lines appear only if the level is lowered. Keywords: log, error message, signature, Serilog, log level.\n\n']
for s in sorted(d):
  lg=d[s].get('logl',[]) or [('?',m,src,'','') for m,src in d[s].get('log',[])]
  if not lg: continue
  L.append(f"## {s}\n\nLogger templates in {s}. Keywords: {s} log, error.\n\n| Level | Message template | Source |\n|---|---|---|\n")
  seen=set()
  for lv,m,src,c,mm in lg:
    if (lv,m) in seen: continue
    seen.add((lv,m)); L.append(f"| {lv} | {m.replace('|','\\|')[:220]} | `{src}` |\n")
  L.append("\n")
open(f'{KB}/inventory/{REPO}-logs.md','w').write(''.join(L))
