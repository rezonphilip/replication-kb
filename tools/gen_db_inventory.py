# usage: python3 -I gen_db_inventory.py <sql.json> <code-extract.json> <repo_name> <kb_root>
# Builds inventory/<repo>-db.md from extract_sql.py output, cross-referenced with the C# extract
# (which service calls which procedure). Names only - never parameter values.
import json, sys, collections, re

sql = json.load(open(sys.argv[1])); code = json.load(open(sys.argv[2]))
REPO, KB = sys.argv[3], sys.argv[4]

def norm(n):
    n = n.replace('[', '').replace(']', '').strip()
    if '.' not in n: n = 'REP.' + n
    s, o = n.split('.', 1); return f'{s.upper()}.{o.upper()}'

def cite(f):  # staged folder "RepX--PAL.DatabaseScripts.Y/..." -> repo path "RepX/PAL.DatabaseScripts.Y/..."
    return f.replace('--', '/', 1)

callers = collections.defaultdict(set)
for svc, v in code.items():
    for n, src in v.get('sp', []):
        callers[norm(n)].add(svc)
params_in_code = {norm(n) for v in code.values() for n, _ in v.get('param', [])}

objs = collections.OrderedDict()   # name -> {kind, defs:[(side,file,line)], columns, params, reads, writes}
for f, r in sql.items():
    side = 'Office' if '.Office' in f.split('/')[0] else 'Vessel'
    owner = f.split('--')[0]
    for o in r['objects']:
        if o['kind'] == 'add_column':
            e = objs.setdefault(o['name'], {'kind': 'table', 'defs': [], 'columns': [], 'params': [], 'reads': set(), 'writes': set(), 'added': []})
            if o['column'] not in e['added']: e['added'].append(o['column'])
            continue
        e = objs.setdefault(o['name'], {'kind': o['kind'], 'defs': [], 'columns': [], 'params': [], 'reads': set(), 'writes': set(), 'added': []})
        e['kind'] = o['kind']
        e['defs'].append((owner, side, cite(f), o['line']))
        if o.get('columns') and not e['columns']: e['columns'] = o['columns']
        if o.get('params') and not e['params']: e['params'] = o['params']
        if o['kind'] in ('procedure', 'function'):
            e['reads'].update(n for n, _ in r['reads']); e['writes'].update(n for n, _ in r['writes'])

seeded = collections.defaultdict(set)
for f, r in sql.items():
    for n in r.get('param_names', []): seeded[n].add(cite(f).split('/')[0] + ' ' + ('Office' if '.Office' in f else 'Vessel'))

SECRET = ('ACCOUNT_KEY', 'CONNECTION_STRING', 'PASSWORD', 'SECRET', 'CREDENTIALS')
out = [f'''---
doc_id: INV-MSREP-DB
type: inventory
mechanism: [smartsync, priority-replication]
components: [ms-rep]
sources: ["MS-REP database scripts snapshot staged 2026-11-11 (no git commit available)"]
status: draft
author: claude
reviewed_by: ""
last_verified: 2026-11-11
---

# MS-REP database inventory

Machine-extracted list of the tables, table types, sequences and stored procedures created by the MS-REP database deployment scripts, with the services that call each procedure. Keywords: database, stored procedure, table, schema REP, Common, CO_Parameters, deployment script.

Generated by `tools/extract_sql.py` + `tools/gen_db_inventory.py`. Do not edit by hand. Values are never recorded; secret-bearing names are marked.

## Summary

Counts of objects found in `RepIntegration/PAL.DatabaseScripts.*` and `RepTransfer/PAL.DatabaseScripts.*`. Keywords: object count, office scripts, vessel scripts.

''']
cnt = collections.Counter(e['kind'] for e in objs.values())
out.append('| Kind | Count |\n|---|---|\n' + ''.join(f'| {k} | {v} |\n' for k, v in sorted(cnt.items())) + '\n')

def section(kind, title, kw):
    items = [(n, e) for n, e in objs.items() if e['kind'] == kind]
    out.append(f'## {title}\n\n{len(items)} {kind} objects. Keywords: {kw}.\n\n')
    for n, e in sorted(items):
        sides = sorted({f'{d[0]} {d[1]}' for d in e['defs']})
        d0 = e['defs'][0] if e['defs'] else None
        line = f'- **`{n}`** — defined in ' + (f'`{d0[2]}#L{d0[3]}`' if d0 else '(columns added only)') + f' ({", ".join(sides)})'
        if kind == 'procedure':
            c = sorted(callers.get(n, []))
            line += f'; called by: {", ".join(c) if c else "no caller found in staged C#"}'
        out.append(line + '\n')
        if e['columns']:
            out.append('  - columns: ' + ', '.join(c.split()[0] for c in e['columns']) + '\n')
        if e['added']:
            out.append('  - columns added by later scripts: ' + ', '.join(c.split()[0] for c in e['added']) + '\n')
        if e['params']:
            out.append('  - parameters: ' + ', '.join(e['params']) + '\n')
        if kind == 'procedure':
            if e['writes']: out.append('  - writes: ' + ', '.join(sorted(e['writes'])) + '\n')
            rd = sorted(e['reads'] - e['writes'] - {'REP.#TEMP'})
            rd = [x for x in rd if '#' not in x]
            if rd: out.append('  - reads: ' + ', '.join(rd) + '\n')
    out.append('\n')

section('table', 'Tables', 'table, columns, REP schema')
section('type', 'Table types', 'user-defined table type, TVP, bulk')
section('sequence', 'Sequences', 'sequence, ID generator')
section('procedure', 'Stored procedures', 'stored procedure, SP, called by')

out.append('## CO_Parameters names seeded by scripts\n\nParameter NAMES inserted or updated by the deployment scripts (values are never recorded here). Keywords: CO_Parameters, seed data, default keys.\n\n| Name | Seeded in | Secret |\n|---|---|---|\n')
for n in sorted(seeded):
    out.append(f'| `{n}` | {", ".join(sorted(seeded[n]))} | {"yes — never copy" if any(s in n for s in SECRET) else ""} |\n')
out.append('\n## Procedures called by code but not found in these scripts\n\nNames referenced in C# that no staged script creates; they may live in another repository or database (for example `PAL_REP`). Keywords: missing procedure, external database.\n\n')
missing = sorted(n for n in callers if n not in objs and n not in params_in_code and re.match(r'^(REP|COMMON)\.[A-Z0-9_]+$', n) and not n.endswith('_TYP'))
out.append(''.join(f'- `{n}` — called by {", ".join(sorted(callers[n]))}\n' for n in missing) + '\n')
open(f'{KB}/inventory/{REPO}-db.md', 'w').write(''.join(out))
print('objects', len(objs), 'missing', len(missing))
