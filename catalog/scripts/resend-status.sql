-- Read-only. Sender view: resend history and manual resend requests for one vessel.
-- Source: RepIntegration/PAL.DatabaseScripts.Office/StoredProcedures/112_PRIORITY_RESEND_DATA.sql
DECLARE @VESSEL_OBJECT_ID BIGINT = :vessel_object_id;

SELECT  TOP 200 H.PACKET_CTR, H.FILE_NAME, H.STATUS AS PACKET_STATUS, ISNULL(H.COMM_TYPE,0) AS COMM_TYPE,
        H.MODIFIED_ON AS PACKET_MODIFIED_ON, L.[COUNT] AS RESEND_COUNT, L.MODIFIED_ON AS LAST_RESEND_ON,
        CASE WHEN ISNULL(L.[COUNT],0) >= 5 THEN 'LIMIT_REACHED' ELSE '' END AS RESEND_LIMIT
FROM    REP.PR_REP_OUT_Packet_HD H WITH (NOLOCK)
LEFT JOIN REP.PR_RESEND_LOG L WITH (NOLOCK) ON L.OUT_PACKET_ID = H.ID
WHERE   H.VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID
  AND   (H.STATUS IN ('ERR','PCK','PND','RED','RND') OR L.ID IS NOT NULL)
ORDER BY H.PACKET_CTR DESC;

SELECT  OUT_PACKET_ID, FILE_NAME, STATUS, MODIFIED_ON
FROM    REP.PR_RESEND_QUEUE WITH (NOLOCK)
WHERE   VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID
ORDER BY MODIFIED_ON DESC;
