-- Read-only. Counts per status (and oldest row) for every MS-REP queue, optionally for one vessel.
-- Pass NULL for all vessels. Status meanings: articles/60-data/ms-rep-status-codes.md
DECLARE @VESSEL_OBJECT_ID BIGINT = :vessel_object_id;

SELECT 'TRACKCHANGE_VESSELS' AS QUEUE_NAME, CAST(STATUS AS VARCHAR(10)) AS STATUS, COUNT(*) AS ROWS_, MIN(MODIFIED_ON) AS OLDEST
FROM REP.PR_TRACKCHANGE_VESSELS WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'OUT_PACKET_HD', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.PR_REP_OUT_Packet_HD WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'TRANSFER_QUEUE', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.REP_TRANSFER_QUEUE WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'AZURE_RES_UPLOAD', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.REP_AZURE_RES_UPLOAD WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'DOWNLOADS', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.REP_Downloads WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'IMPORT_QUEUE', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.PR_REP_IMPORT_QUEUE WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
UNION ALL
SELECT 'MISSING_PACKETS', CAST(STATUS AS VARCHAR(10)), COUNT(*), MIN(MODIFIED_ON)
FROM REP.PR_REP_Missing_Packets WITH (NOLOCK) WHERE @VESSEL_OBJECT_ID IS NULL OR VESSEL_OBJECT_ID = @VESSEL_OBJECT_ID GROUP BY STATUS
ORDER BY QUEUE_NAME, STATUS;
